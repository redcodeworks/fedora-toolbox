#!/usr/bin/env bash
# Static checks of the dna-toolbox server stack (no container runtime, no host access): the shipped
# Quadlet and compose files render, images are pinned, ports are offset and local, no secrets in files.
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
DNA_STACK_ROOT="${here}/dna-toolbox/stack" "${here}/dna-toolbox/stack/bin/dna-stack" check
echo "ok   dna-stack static checks"

# dna-toolbox: versions.env parses, the Java package matches DNA_JAVA_VERSION, downloads are pinned
tb="${here}/dna-toolbox"
# shellcheck source=/dev/null
( set -a; . "${tb}/versions.env"; set +a
  grep -qx "java-${DNA_JAVA_VERSION}-openjdk" "${tb}/packages/optional.txt" ) \
    || { echo "FAIL optional.txt lacks java-<DNA_JAVA_VERSION>-openjdk" >&2; exit 1; }
while IFS='|' read -r name _ url sha _; do
    [[ -z "${name}" || "${name}" == \#* ]] && continue
    [[ "${url}" == https://* && "${sha}" =~ ^[0-9a-f]{64}$ ]] || { echo "FAIL downloads.lock: ${name} is not pinned by https URL and sha256" >&2; exit 1; }
done < "${tb}/downloads.lock"
echo "ok   dna-toolbox versions.env, java package and download pins"

# up, down and remove: checklist defaults, dependency warnings, non-interactive paths. The host is
# replaced by a stub (no runtime, no real host command is ever run).
(
    tmp=$(mktemp -d); trap 'rm -rf "${tmp}"' EXIT
    export DNA_STATE="${tmp}/state" DNA_QUADLET_DIR="${tmp}/q" DNA_STACK_ROOT="${here}/dna-toolbox/stack"
    # shellcheck source=/dev/null
    . "${here}/dna-toolbox/stack/bin/dna-stack"
    # shellcheck disable=SC2329,SC2034  # stub called by the sourced script, which reads these globals
    detect() { HOSTX=direct; RT=podman; MODE=quadlet; }
    calls="${tmp}/calls"; running="${tmp}/running"; : > "${calls}"
    # shellcheck disable=SC2329  # stub called by the sourced script
    host() {
        echo "$*" >> "${calls}"
        case "$*" in
            "systemctl --user is-active --quiet dna-"*) local all="$*"; local u=${all##* dna-}; grep -qx "${u%.service}" "${running}" ;;
            *) return 0 ;;
        esac
    }
    mkdir -p "${DNA_STATE}" "${DNA_QUADLET_DIR}"
    printf '%s\n' postgres seaweedfs lakekeeper trino > "${DNA_STATE}/selected"
    t() { echo "FAIL $*" >&2; exit 1; }
    o="" ; reset() { : > "${calls}"; }

    # up with everything stopped: no terminal, no names, no --yes -> warning, checklist empty, nothing started
    : > "${running}"; reset
    o=$(cmd_up </dev/null 2>&1) || true
    grep -q 'WARNING: some services depend on others' <<<"${o}" || t "up: dependency warning missing"
    grep -q 'lakekeeper needs postgres, seaweedfs' <<<"${o}" || t "up: dependency map missing"
    grep -q 'dry run' <<<"${o}" || t "up: no dry-run message without a terminal"
    ! grep -q 'systemctl --user start' "${calls}" || t "up: started something by default"
    # up trino adds its dependencies and says so
    reset; o=$(cmd_up trino </dev/null 2>&1)
    grep -q 'also starting the dependencies: postgres seaweedfs lakekeeper' <<<"${o}" || t "up: dependencies not announced"
    [[ $(grep -c 'systemctl --user start' "${calls}") -eq 4 ]] || t "up trino did not start four services"

    # down postgres while lakekeeper runs: dependents warning, dry run without --yes
    printf '%s\n' postgres seaweedfs lakekeeper trino > "${running}"; reset
    o=$(cmd_down postgres </dev/null 2>&1) || true
    grep -q 'WARNING: .*depend.* on postgres' <<<"${o}" || t "down: dependents warning missing"
    grep -q 'dry run' <<<"${o}" || t "down: not a dry run without --yes"
    ! grep -q 'systemctl --user stop' "${calls}" || t "down stopped a service without --yes"
    # with --yes only the named service is stopped (no silent cascade)
    reset; o=$(cmd_down postgres --yes </dev/null 2>&1)
    [[ $(grep -c 'systemctl --user stop' "${calls}") -eq 1 ]] || t "down --yes cascaded or did nothing"
    grep -q 'stop dna-postgres.service' <<<"${o}" || t "down --yes did not stop postgres"
    # down with no names, no terminal, no --yes: checklist empty -> nothing stopped
    reset; o=$(cmd_down </dev/null 2>&1) || true
    ! grep -q 'systemctl --user stop' "${calls}" || t "down stopped something by default"
    # naming a leaf service stops it without a dependents warning
    reset; o=$(cmd_down trino --yes </dev/null 2>&1)
    ! grep -q 'WARNING: .*depend' <<<"${o}" || t "down trino: unexpected dependents warning"

    # remove: dry run by default, dependents warning, nothing deleted
    : > "${DNA_QUADLET_DIR}/dna-postgres.container"; printf '# Generated by dna-stack\n' > "${DNA_QUADLET_DIR}/dna-postgres.container"
    reset; o=$(cmd_remove </dev/null 2>&1) || true
    grep -q 'dry run' <<<"${o}" || t "remove: not a dry run by default"
    [[ -f "${DNA_QUADLET_DIR}/dna-postgres.container" ]] || t "remove deleted a file in a dry run"
    reset; o=$(cmd_remove postgres </dev/null 2>&1) || true
    grep -q 'WARNING: .*depend.* on postgres' <<<"${o}" || t "remove: dependents warning missing"
    [[ -f "${DNA_QUADLET_DIR}/dna-postgres.container" ]] || t "remove deleted postgres without --yes"
    # volumes are never deleted without a terminal (typed yes)
    reset; cmd_remove postgres --yes --volumes </dev/null >/dev/null 2>&1 || true
    ! grep -q 'volume rm' "${calls}" || t "remove deleted a volume without a typed yes"
    echo "ok   dna-stack up/down/remove checklist and dependency warnings"
) || exit 1
